  // i18n/runtime.ts
  var dictionaries = { pt, en };
  var STORAGE_KEY = "pds_lang";
  function t(dict, key) {
    if (!key) return null;
    if (key in dict) return dict[key];
    console.warn(`[i18n] Missing key: ${key}`);
    return null;
  }
  var currentLang = "pt";
  function getLang() {
    return currentLang;
  }
  function translate(key) {
    const dict = dictionaries[currentLang] ?? dictionaries.pt;
    return t(dict, key) ?? key;
  }
  function setLanguage(lang) {
    currentLang = lang;
    const dict = dictionaries[lang] ?? dictionaries.pt;
    document.documentElement.lang = lang === "en" ? "en" : "pt-PT";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const value = t(dict, el.getAttribute("data-i18n"));
      if (value == null) return;
      const attr = el.getAttribute("data-i18n-attr");
      if (attr) {
        el.setAttribute(attr, value);
        return;
      }
      el.innerHTML = value;
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      const value = t(dict, el.getAttribute("data-i18n-alt"));
      if (value != null) el.setAttribute("alt", value);
    });
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      const active = btn.dataset.lang === lang;
      btn.classList.toggle("active", active);
      btn.classList.toggle("text-gray-500", !active);
    });
    localStorage.setItem(STORAGE_KEY, lang);
    document.dispatchEvent(new CustomEvent("pds:langchange", { detail: { lang } }));
  }
  function initI18n() {
    const saved = localStorage.getItem(STORAGE_KEY);
    const lang = saved === "en" ? "en" : "pt";
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.addEventListener("click", () => {
        const next = btn.dataset.lang === "en" ? "en" : "pt";
        setLanguage(next);
      });
    });
    setLanguage(lang);
    window.pdsI18n = { t: translate, getLang, setLanguage };
  }

  // i18n/main.ts
  initI18n();
